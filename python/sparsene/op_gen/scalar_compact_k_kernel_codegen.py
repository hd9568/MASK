"""Experimental complete kernel built around scheduled NVIR stage nodes.

This is not the production OPIR->NVIR code generator. The original DSL is
validated by the strict host planner; outer WMMA/launch code is specialized
by this prototype. It must not be marked production-integrated.
"""
from __future__ import annotations
from .scalar_compact_k_lowering import ScalarCompactKPlan
from .nvir.composed_k_ops import emit_scheduled_composed_k_stage


def emit_experimental_full_kernel(plan: ScalarCompactKPlan, *, refine: bool = False) -> str:
    if not isinstance(plan,ScalarCompactKPlan) or (plan.blk_m,plan.blk_k,plan.blk_k_i)!=(16,8,4):
        raise ValueError('only the validated 16x8, inner-K4 profile is supported')
    stage=emit_scheduled_composed_k_stage(scalar_offsets=True,share_a=True)
    if refine:
        stage=stage.replace('A[x]=wmma::__float_to_tf32(v);', 'A[x]=wmma::__float_to_tf32(v); ALO[x]=wmma::__float_to_tf32(v-A[x]);')
        stage=stage.replace('BT[x]=wmma::__float_to_tf32(v);', 'BT[x]=wmma::__float_to_tf32(v); BTLO[x]=wmma::__float_to_tf32(v-BT[x]);')
    source = '''// Experimental full kernel: NVIR-scheduled stage + specialized WMMA shell.
// Not generated by the production OPIR->NVIR compiler.
#include <mma.h>
#include <cstdint>
__global__ void compute_tc(int M,int N,const int32_t* wp,const int32_t* bp,const int64_t* cols,const float* val,const int64_t* sp,const int32_t* si,const int32_t* composed,const float* B,float* C) {
 namespace wmma=nvcuda::wmma;
 int w=blockIdx.x, warp=threadIdx.x/32, nbase=blockIdx.y*64+warp*16, lane=threadIdx.x%32;
 __shared__ __align__(32) float Aall[16*8]; float* A=Aall;
 __shared__ __align__(32) float BTall[4*8*16]; float* BT=BTall+warp*8*16;
 __shared__ __align__(32) float OUTall[4*16*16]; float* OUT=OUTall+warp*16*16;
 wmma::fragment<wmma::accumulator,16,16,8,float> acc;
 wmma::fill_fragment(acc,0.0f);
 for(int64_t q=wp[w];q<wp[w+1];q++) {
''' + stage + '''
  wmma::fragment<wmma::matrix_a,16,16,8,wmma::precision::tf32,wmma::row_major> a;
  wmma::fragment<wmma::matrix_b,16,16,8,wmma::precision::tf32,wmma::row_major> b;
  wmma::load_matrix_sync(a,A,8); wmma::load_matrix_sync(b,BT,16);
  wmma::mma_sync(acc,a,b,acc); __syncthreads();
 }
 wmma::store_matrix_sync(OUT,acc,16,wmma::mem_row_major); __syncwarp();
 for(int x=lane;x<256;x+=32) {int row=w*16+x/16,n=nbase+x%16; if(row<M&&n<N) C[(int64_t)row*N+n]=OUT[x];}
}
'''
    if refine:
        source=source.replace('__shared__ __align__(32) float Aall[16*8]; float* A=Aall;', '__shared__ __align__(32) float Aall[16*8]; float* A=Aall; __shared__ __align__(32) float ALO[16*8];')
        source=source.replace('__shared__ __align__(32) float BTall[4*8*16]; float* BT=BTall+warp*8*16;', '__shared__ __align__(32) float BTall[4*8*16]; float* BT=BTall+warp*8*16; __shared__ __align__(32) float BTLOall[4*8*16]; float* BTLO=BTLOall+warp*8*16;')
        source=source.replace('wmma::mma_sync(acc,a,b,acc); __syncthreads();', 'wmma::mma_sync(acc,a,b,acc); wmma::load_matrix_sync(a,ALO,8); wmma::mma_sync(acc,a,b,acc); wmma::load_matrix_sync(a,A,8); wmma::load_matrix_sync(b,BTLO,16); wmma::mma_sync(acc,a,b,acc); __syncthreads();')
    return source


def emit_scalar_fp32_diagnostic(plan: ScalarCompactKPlan) -> str:
    """Full-FP32 diagnostic sharing identical composed ABI and launch grid."""
    if not isinstance(plan,ScalarCompactKPlan) or (plan.blk_m,plan.blk_k,plan.blk_k_i)!=(16,8,4):
        raise ValueError('only the validated 16x8, inner-K4 profile is supported')
    return '''// Full FP32 diagnostic; not a high-performance generated backend.
#include <cstdint>
__global__ void compute_tc(int M,int N,const int32_t* wp,const int32_t* bp,const int64_t* cols,const float* val,const int64_t* sp,const int32_t* si,const int32_t* composed,const float* B,float* C) {
 int w=blockIdx.x,nbase=blockIdx.y*64;
 for(int x=threadIdx.x;x<16*64;x+=blockDim.x) {
  int row=w*16+x/64,n=nbase+x%64;if(row>=M||n>=N)continue;
  int r=row%16;float sum=0;
  for(int q=wp[w];q<wp[w+1];q++) for(int z=bp[q]/4;z<bp[q+1]/4;z++) for(int j=0;j<4;j++) {
   int k=composed[z*4+j]; if(k>=0) sum=fmaf(val[(z*16+r)*4+j],B[(int64_t)k*N+n],sum);
  }
  C[(int64_t)row*N+n]=sum;
 }
}
'''
